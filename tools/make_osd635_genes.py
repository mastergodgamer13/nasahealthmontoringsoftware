"""Builds js/osd635-genes.js from the OSDR differential-expression file of OSD-635.

Usage:  python3 -I tools/make_osd635_genes.py GLDS-608_rna_seq_differential_expression_GLbulkRNAseq.csv js/osd635-genes.js

Keeps, for every gene in the file: Ensembl id, symbol, gene name, log2 fold change and adjusted p-value of
"(Space Flight) v (Ground Control)", and the group mean normalized counts. Numbers are rounded to 6 significant digits
(documented in the output). "NA" becomes null / empty. Nothing is filtered or recomputed.
"""
import csv, json, math, sys

SRC_NAME = 'GLDS-608_rna_seq_differential_expression_GLbulkRNAseq.csv'
CONTRAST = '(Space Flight)v(Ground Control)'
COLS = ['ensembl', 'symbol', 'name', 'log2fc', 'padj', 'flightMean', 'groundMean']


def num(x):
    try:
        v = float(x)
    except (TypeError, ValueError):
        return None
    return float(format(v, '.6g')) if math.isfinite(v) else None


def text(x):
    return '' if x in ('NA', '') else x


def main(src, dst):
    with open(src, encoding='utf-8', newline='') as f:
        rows = [[r['ENSEMBL'], text(r['SYMBOL']), text(r['GENENAME']),
                 num(r['Log2fc_' + CONTRAST]), num(r['Adj.p.value_' + CONTRAST]),
                 num(r['Group.Mean_(Space Flight)']), num(r['Group.Mean_(Ground Control)'])]
                for r in csv.DictReader(f)]
    data = {
        'study': 'OSD-635', 'source': SRC_NAME,
        'contrast': 'Space Flight vs Ground Control (log2 fold change > 0: higher in Space Flight)',
        'precision': '6 significant digits', 'cols': COLS, 'rows': rows,
    }
    body = json.dumps(data, ensure_ascii=False, separators=(',', ':'))
    with open(dst, 'w', encoding='utf-8') as f:
        f.write('/* osd635-genes.js — GENERATED by tools/make_osd635_genes.py from ' + SRC_NAME + '. Do not edit by hand. */\n')
        f.write("(function (root) { 'use strict'; var D = " + body + ";\n")
        f.write("  if (typeof module !== 'undefined' && module.exports) module.exports = D; else root.Osd635Genes = D;\n")
        f.write("})(typeof window !== 'undefined' ? window : globalThis);\n")
    print(len(rows), 'genes written to', dst)


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
