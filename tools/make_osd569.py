"""Generate js/osd569-data.js from the OSD-569 files (CBC csv, long-read gene xlsx, nanopore assay table).
Usage: python3 -I tools/make_osd569.py <cbc.csv> <genes.xlsx> <nanopore_assay.txt> <out.js>
Values are copied as published; only fields that are obviously misplaced in the source are left empty (listed in `excluded`)."""
import csv, json, sys, openpyxl
cbc_csv, xlsx, assay, out = sys.argv[1:5]
TP = ['L-92', 'L-44', 'L-3', 'R+1', 'R+45', 'R+82', 'R+194']
A = [  # id, csv column stem, unit, decimals
    ('wbc', 'white_blood_cell_count', '10³/µL', 1), ('rbc', 'red_blood_cell_count', '10⁶/µL', 2),
    ('hgb', 'hemoglobin', 'g/dL', 1), ('hct', 'hematocrit', '%', 1), ('plt', 'platelet_count', '10³/µL', 0),
    ('mcv', 'mcv', 'fL', 1), ('neut', 'absolute_neutrophils', 'cells/µL', 0), ('lymph', 'absolute_lymphocytes', 'cells/µL', 0)]
# C003 L-92: the row is shifted in the source (absolute counts and platelet/MPV/RDW values sit in neighbouring columns).
EXCLUDE = {('C003', 'L-92'): {'neut': 'misplaced', 'lymph': 'misplaced', 'plt': 'misplaced'}}
def num(s):
    s = (s or '').strip()
    return float(s) if s != '' else None
crew = {}
for r in csv.DictReader(open(cbc_csv, encoding='utf-8-sig')):
    c, _, rest = r['Sample Name'].partition('_whole-blood_'); tp = rest[:-4]
    d = {}
    for aid, stem, unit, dec in A:
        col = lambda k: next((x for x in r if x.startswith(stem + '_' + k + '_')), None)
        v, lo, hi = num(r[col('value')]), num(r[col('range_min')]), num(r[col('range_max')])
        if EXCLUDE.get((c, tp), {}).get(aid): v = None
        d[aid] = [v, lo, hi]
    crew.setdefault(c, {})[tp] = d
cbc = {c: {a[0]: {'values': [crew[c][t][a[0]][0] for t in TP], 'lo': [crew[c][t][a[0]][1] for t in TP], 'hi': [crew[c][t][a[0]][2] for t in TP]} for a in A} for c in sorted(crew)}
sex = {'C001': 'M', 'C002': 'F', 'C003': 'F', 'C004': 'M'}
# gene results: DESeq2 and pipeline-transcriptome-de, thresholds from the project (adj p <= 0.05, |log2FC| >= 1.5)
wb = openpyxl.load_workbook(xlsx, read_only=True)
comps = []; listed = {}
for ws in wb:
    rows = list(ws.iter_rows(values_only=True))
    cmpname = rows[3][1]; hdr = rows[6:9]; data = rows[10:]
    col = {(hdr[1][j], hdr[2][j]): j for j in range(len(hdr[0])) if hdr[1][j] in ('DESeq2', 'pipeline-transcriptome-de')}
    entry = {'id': ws.title, 'cmp': cmpname, 'genes': len(data), 'tools': {}}
    for tool in ('DESeq2', 'pipeline-transcriptome-de'):
        l, p = col[(tool, 'log2FC')], col[(tool, 'adjusted p-value')]
        c = {'up': 0, 'down': 0, 'below': 0, 'ns': 0, 'nodata': 0}; hits = []
        for r in data:
            try: a = float(r[l]); b = float(r[p])
            except (TypeError, ValueError): c['nodata'] += 1; continue
            if b > 0.05: c['ns'] += 1
            elif a >= 1.5: c['up'] += 1; hits.append([r[0].split('.')[0], float('%.6g' % a), float('%.6g' % b)])
            elif a <= -1.5: c['down'] += 1; hits.append([r[0].split('.')[0], float('%.6g' % a), float('%.6g' % b)])
            else: c['below'] += 1
        entry['tools'][tool] = c
        if ws.title == 'I4-FP3' and tool == 'pipeline-transcriptome-de': listed = sorted(hits, key=lambda h: -abs(h[1]))
    comps.append(entry)
# nanopore assay summary
lines = [l.rstrip('\n').split('\t') for l in open(assay, encoding='utf-8') if l.strip()]
h = lines[0]; ri = h.index('Parameter Value[QA Score]'); di = h.index('Parameter Value[Read Depth]')
rin = [float(l[ri]) for l in lines[1:]]; dep = [int(l[di]) for l in lines[1:]]
nano = {'samples': len(rin), 'rinMin': min(rin), 'rinMax': max(rin), 'depthMin': min(dep), 'depthMax': max(dep)}
data = {'study': 'OSD-569', 'tp': TP, 'sex': sex, 'analytes': [{'id': a[0], 'unit': a[2], 'decimals': a[3]} for a in A],
        'cbc': cbc, 'excluded': [{'crew': k[0], 'tp': k[1], 'fields': sorted(v)} for k, v in EXCLUDE.items()],
        'comparisons': comps, 'listed': {'comparison': 'I4-FP3', 'tool': 'pipeline-transcriptome-de', 'genes': listed}, 'nanopore': nano}
open(out, 'w', encoding='utf-8').write('/* generated by tools/make_osd569.py — values as published (see README) */\n(function (r) { r.Osd569Data = ' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + '; })(typeof window !== "undefined" ? window : globalThis);\nif (typeof module !== "undefined" && module.exports) module.exports = (typeof window !== "undefined" ? window : globalThis).Osd569Data;\n')
print('ok', nano, len(comps), len(listed))
